import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { execFileSync } from 'node:child_process'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const evidence = process.env.PVL_E2E_FIXTURE === '1' ? 'test-results/fixture-screenshots' : 'docs/evidence/d08/regression'
async function restoreScreenshotViewport(page: import('@playwright/test').Page) {
  await page.evaluate(() => {
    (document.activeElement as HTMLElement)?.blur()
    window.scrollTo(0, 0)
  })
}

test('real PDF upload → page → preview → inspect → confirm → JSONL → persistence', async ({ page, request }) => {
  test.setTimeout(60000)
  const python = process.platform === 'win32' ? '.venv/Scripts/python.exe' : 'python'
  execFileSync(python, ['scripts/create_pdf_fixture.py'], { env: { ...process.env, PYTHONUTF8: '1' } })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/documents')
  await expect(page.getByRole('button', { name: 'Choose file' })).toBeEnabled()
  await page.getByLabel('Choose document file').setInputFiles(resolve('.cache/e2e-fixtures/vietnamese.pdf'))
  await expect(page.getByRole('heading', { name: 'vietnamese.pdf', exact: true })).toBeVisible()
  await expect(page.getByLabel('Page 1 text')).toContainText('Cơ sở dữ liệu vector')
  await page.getByRole('button', { name: 'Next page' }).click()
  await expect(page.getByLabel('Page 2 text')).toContainText('Trang 2')
  await page.getByRole('button', { name: 'Generate preview' }).click()
  await expect(page.getByText('DRAFT · V1', { exact: true })).toBeVisible()
  await page.getByRole('group', { name: 'Generated chunks' }).getByRole('button').nth(1).click()
  await expect(page.getByLabel('Full chunk text').locator('mark')).toBeVisible()
  await page.getByRole('button', { name: 'Copy chunk text' }).click()
  await expect(page.getByRole('status')).toContainText('Chunk text copied.')
  const tokenizer = await (await request.get('http://127.0.0.1:8001/api/tokenizer')).json()
  if (process.env.PVL_E2E_FIXTURE === '1') expect(tokenizer.mode).toBe('test-fixture-not-e5')
  else expect(tokenizer.mode).toBe('e5')
  await page.getByRole('button', { name: 'Confirm / Save' }).click()
  await expect(page.getByText('CONFIRMED · V1', { exact: true })).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Download JSONL' }).click()
  const download = await downloadPromise
  const file = await download.path()
  const content = await readFile(file!, 'utf8')
  const chunks = content.trim().split('\n').map(line => JSON.parse(line))
  expect(chunks.length).toBeGreaterThan(1)
  expect(chunks[0]).toMatchObject({ page_start: 1, index: 0, chunk_size: 300, overlap: 50 })
  expect(chunks.every(chunk => chunk.model_token_count <= 512 && chunk.token_count <= 300)).toBeTruthy()
  await mkdir(evidence, { recursive: true })
  if (tokenizer.mode === 'e5') await writeFile('docs/evidence/d08/regression/synthetic-confirmed.jsonl', content, 'utf8')
  await page.evaluate(() => document.fonts.ready)
  await restoreScreenshotViewport(page)
  await page.screenshot({ path: `${evidence}/desktop-1440.png`, fullPage: true })
  const accessibility = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(accessibility.violations.filter(v => ['serious', 'critical'].includes(v.impact ?? ''))).toEqual([])
  await page.getByLabel('Chunk size (tokens)').fill('180')
  await expect(page.getByText(/Configuration changed/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Confirm / Save' })).toBeDisabled()
  await page.getByRole('button', { name: 'Generate preview' }).click()
  await expect(page.getByText('DRAFT · V2', { exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Download JSONL' })).toHaveCount(0)
  await page.reload()
  await page.getByRole('group', { name: 'Stored documents' }).getByRole('button', { name: /vietnamese.pdf/ }).click()
  await expect(page.getByText('CONFIRMED · V1', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Chunk size (tokens)')).toHaveValue('300')
  await page.setViewportSize({ width: 390, height: 844 })
  await restoreScreenshotViewport(page)
  await page.screenshot({ path: `${evidence}/mobile-390.png`, fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: 'Delete selected document' }).click()
  await page.getByRole('button', { name: 'Cancel' }).click()
  await expect(page.getByRole('heading', { name: 'vietnamese.pdf', exact: true })).toBeVisible()
})

test('TXT/BOM upload, validation error, and confirmed deletion', async ({ page }) => {
  await page.goto('/documents')
  await expect(page.getByRole('button', { name: 'Choose file' })).toBeEnabled()
  await page.getByLabel('Choose document file').setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('\uFEFFTiếng Việt.\r\n\r\nMột trang logic.') })
  await expect(page.getByLabel('Page 1 text')).toContainText('Tiếng Việt.')
  await page.getByLabel('Overlap (source tokens)').fill('300')
  await expect(page.getByRole('button', { name: 'Generate preview' })).toBeDisabled()
  await expect(page.getByRole('alert')).toContainText('smaller than size')
  await page.getByLabel('Overlap (source tokens)').fill('50')
  await page.getByRole('button', { name: 'Generate preview' }).click()
  await expect(page.getByText('DRAFT · V1', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('group', { name: 'Stored documents' }).getByRole('button', { name: /notes.txt/ }).click()
  await expect(page.getByText('DRAFT · V1', { exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Download JSONL' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Delete selected document' }).click()
  await page.getByRole('button', { name: 'Confirm delete' }).click()
  await expect(page.getByRole('heading', { name: 'notes.txt', exact: true })).toHaveCount(0)
})
